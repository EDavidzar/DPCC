    private void FillPanel() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn(" idregistro ");
        model.addColumn(" Clente ");
        model.addColumn(" Empresa ");
        model.addColumn(" Procedimiento de acceso específico ");
        model.addColumn(" Procedimiento de control específico ");
        model.setRowCount(0);
        int index = 1;
        if (!DEST.isEmpty()) {
            ListIterator<String> dli = DEST.listIterator();
            while (dli.hasNext()) {
                String TheNext = " " + dli.next() + " ";
                var Number = String.format("%03d", index);
                model.addRow(new Object[]{Number, TheNext});
                index++;
            }
            JPTable.setModel(model);
        }
        AddEmptyRow();

    }

    private void LoadList() {
        //SELECT * FROM ccpd_security_measures.list_cat_desttransint;
        PConfig.setDBName("ccpd_security_measures");
        DBMSAP = new FDBManExtra(PConfig.getSQLURL(), PConfig.getAdminDBPassword(), PConfig.getDBName(), PConfig.getAdminDBName(), FDBManExtra.DB_MYSQL_Selected);
        DEST = DBMSAP.LoadList("specificcontrolaccessprocedures","idspecificcontrolaccessprocedures" );

    }

    private void UpdateDBWithTableData() {
        int ntf = AcceptInformation("¿Está seguro de que quiere actualizar los datos?");
        if (ntf == mconfyes) {
            UpdateDBData();
        }
    }

    void AddEmptyRow() {
        int index = JPTable.getModel().getRowCount() + 1;
        DefaultTableModel model = (DefaultTableModel) JPTable.getModel();
        var Number = String.format("%03d", index);
        model.addRow(new Object[]{Number, ""});
    }

    private void InsertRow() {
        int index = JPTable.getModel().getRowCount() - 1;
        String idspecificcontrolaccessprocedures = (String) JPTable.getModel().getValueAt(index, 0);
        String sidclient = (String) JPTable.getModel().getValueAt(index, 1);
        String sidenterprise = (String) JPTable.getModel().getValueAt(index, 2);
        String sspecificaccessprocedure = (String) JPTable.getModel().getValueAt(index, 3);
        String sspecificcontrolprocedure = (String) JPTable.getModel().getValueAt(index, 4);

        //CL_DBCV CamposPanel=new CL_DBCV();
        CLAllObjectList<CL_DBCV> List_CamposPanel = new CLAllObjectList<>();
        List_CamposPanel.add(new CL_DBCV(idspecificcontrolaccessprocedures, idspecificcontrolaccessprocedures));
        List_CamposPanel.add(new CL_DBCV(sidclient, idspecificcontrolaccessprocedures));
        List_CamposPanel.add(new CL_DBCV(sidenterprise, idspecificcontrolaccessprocedures));
        List_CamposPanel.add(new CL_DBCV(sspecificaccessprocedure, idspecificcontrolaccessprocedures));
        List_CamposPanel.add(new CL_DBCV(sspecificcontrolprocedure, idspecificcontrolaccessprocedures));

        DBMSAP.InsertDatainDB("specificcontrolaccessprocedures", List_CamposPanel);
        AddEmptyRow();
    }

    private void DeleteRow() {
        int ntf = AcceptInformation("¿Está seguro de que quiere borrar la fila seleccionada?");
        if (ntf == mconfyes) {
            int index = JPTable.getSelectedRow();
            ((DefaultTableModel) JPTable.getModel()).removeRow(index);
        }
    }

    private void UpdateDBData() {
        int totalindex = JPTable.getModel().getRowCount();
        int index = 0;
        CLAllObjectList<CL_DBCV> List_CamposPanel = new CLAllObjectList<>();
        while (index < totalindex) {
            String idspecificcontrolaccessprocedures = (String) JPTable.getModel().getValueAt(index, 0);
            String ssidclient = (String) JPTable.getModel().getValueAt(index, 1);
            String ssidenterprise = (String) JPTable.getModel().getValueAt(index, 2);
            String sspecificaccessprocedure = (String) JPTable.getModel().getValueAt(index, 3);
            String sspecificcontrolprocedure = (String) JPTable.getModel().getValueAt(index, 4);

            if (!"".equals(ssidclient)) {
                List_CamposPanel.add(new CL_DBCV(ssidclient, idspecificcontrolaccessprocedures));
            }
            if (!"".equals(ssidenterprise)) {
                List_CamposPanel.add(new CL_DBCV(ssidenterprise, idspecificcontrolaccessprocedures));
            }
            if (!"".equals(sspecificaccessprocedure)) {
                List_CamposPanel.add(new CL_DBCV(sspecificaccessprocedure, idspecificcontrolaccessprocedures));
            }
            if (!"".equals(sspecificcontrolprocedure)) {
                List_CamposPanel.add(new CL_DBCV(sspecificcontrolprocedure, idspecificcontrolaccessprocedures));
            }

            index++;
        }
        DBMSAP.DeleteDataTable("specificcontrolaccessprocedures");
        DBMSAP.InsertDatainDB("specificcontrolaccessprocedures", List_CamposPanel);
    }
