    void InsertComlumnList(Panel_TableDBManager ptdbm, String tmpDB, String tmpDBTable, String Column, int colnum) {
        JComboBox TestComboBox = new JComboBox();
        PConfig.setDBName(tmpDB);
        FDBManExtra DBMSAP = new FDBManExtra(PConfig.getSQLURL(), PConfig.getAdminDBPassword(), PConfig.getDBName(), PConfig.getAdminDBName(), FDBManExtra.DB_MYSQL_Selected);
        CLAllObjectList<String> IDX = DBMSAP.LoadList(tmpDBTable, Column);
        TableColumn typemedia = ptdbm.getJPTable().getColumnModel().getColumn(colnum);
        for (String item : IDX) {
            TestComboBox.addItem(item);
        }
        TestComboBox.setSelectedIndex(Integer.parseInt((String) ptdbm.getJPTable().getModel().getValueAt(0, colnum)) - 1);
        typemedia.setCellEditor(new DefaultCellEditor(TestComboBox));
    }
