    void RemoveUnneededColumns(Panel_TableDBManager tmpPanel, int itimes) {
        for (int it = 0; it < itimes; it++) {
            tmpPanel.getJPTable().removeColumn(tmpPanel.getJPTable().getColumnModel().getColumn(0));
        }
    }

    void SetCellValue(Panel_TableDBManager tmpPanel, int x, int y, String Content) {
        tmpPanel.getJPTable().setValueAt(Content, y, x);

    }

    void RemoveUnneededColumnsselected(Panel_TableDBManager tmpPanel, int icolumn) {
        tmpPanel.getJPTable().removeColumn(tmpPanel.getJPTable().getColumnModel().getColumn(icolumn));
    }
