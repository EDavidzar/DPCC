    private void FillPanel() {
        DefaultTableModel tmodel = new DefaultTableModel();
        for (int idx = 0; idx < ColumnsName.size(); idx++) {
            Object[] cdata = CLIOP.get(idx).toArray();
            tmodel.addColumn(" " + ColumnsName.get(idx) + " ", cdata);
        }
        getJPTable().setModel(tmodel);
        AddEmptyRow();
        //ShowDInfo("rellenado panel");

    }

    private void LoadList() {
        //SELECT * FROM ccpd_lists.list_cat_desttransint;
        PConfig.setDBName("ccpd_registers");
        DBManager = new FDBManExtra(PConfig.getSQLURL() + ActualDBName, PConfig.getAdminDBPassword(), ActualDBName, PConfig.getAdminDBName(), FDBManExtra.DB_MYSQL_Selected);
        ColumnsName = DBManager.GetColumnsName(ActualDBTable);
        CLIOP = DBManager.LoadList_Table(ActualDBName, ActualDBTable, ColumnsName);
        //ShowDInfo("Cargando datos ...");
    }

    private void UpdateDBWithTableData() {
        int ntf = AcceptInformation("¿Está seguro de que quiere actualizar los datos?");
        if (ntf == mconfyes) {
            UpdateDBData();
        }
    }

    void AddEmptyRow() {
        DefaultTableModel model = (DefaultTableModel) getJPTable().getModel();
        int count = ColumnsName.size();
        Vector rowData = new Vector();
        for (int idx = 0; idx < count; idx++) {
            rowData.add(null);
        }
        model.addRow(rowData);
    }

    private void InsertRow() {
        int index = getJPTable().getModel().getRowCount() - 1;
        String sIndex = (String) getJPTable().getModel().getValueAt(index, 0);
        CLAllObjectList<CL_DBCV> List_CamposPanel = new CLAllObjectList<>();
        int CLS = getJPTable().getModel().getColumnCount() - 1;
        for (int idx = 0; idx < CLS; idx++) {
            String sOperations = (String) getJPTable().getModel().getValueAt(index, idx + 1);
            List_CamposPanel.add(new CL_DBCV(sOperations, sIndex));
        }
        DBManager.InsertDatainDB("dbclients", List_CamposPanel);
        AddEmptyRow();
    }

    private void DeleteRow() {
        int ntf = AcceptInformation("¿Está seguro de que quiere borrar la fila seleccionada?");
        if (ntf == mconfyes) {
            int index = getJPTable().getSelectedRow();
            ((DefaultTableModel) getJPTable().getModel()).removeRow(index);
        }
    }

    private void UpdateDBData() {
        DefaultTableModel tmodel = (DefaultTableModel) getJPTable().getModel();
      //  if (TableUpdated) { TableUpdated CODE NOT WORKING, WHY???
            for (int col = 0; col < ColumnsName.size(); col++) {
                for (int row = firstRowupdated; row <= lastRowupdated; row++) {
                    CLAllObjectList<CL_DBCV> FieldList = new CLAllObjectList<>();
                    if (tmodel.getValueAt(row, col) instanceof String) {
                        String sTheRowElement = (String) tmodel.getValueAt(row, col);
                        CLIOP.get(col + 1).set(row + 1, sTheRowElement);
                        CL_DBCV Field = new CL_DBCV(ColumnsName.get(col + 1), sTheRowElement);
                        FieldList.add(Field);
                    } else if (tmodel.getValueAt(row, col) instanceof JComboBox) {
                        JComboBox jcbTheRowElement = (JComboBox) tmodel.getValueAt(row, col);
                        String sTheRowElement = Integer.toString(jcbTheRowElement.getSelectedIndex());
                        CLIOP.get(col + 1).set(row + 1, sTheRowElement);

                        CL_DBCV Field = new CL_DBCV(ColumnsName.get(col + 1), sTheRowElement);
                        FieldList.add(Field);

                    }
                    DBManager.UpdateTable(ActualDBTable, FieldList);
                    FieldList.clear();
                }

        //    }

            //  CLIOP = DBManager.LoadList_Table(ActualDBName, ActualDBTable, Columns, ActualClient, ActualEnterprise);
        }

    }

    private void LoadList(String ActualClient, String ActualEnterprise) {

        //SELECT * FROM ccpd_lists.list_cat_desttransint;
        PConfig.setDBName(ActualDBName);
        DBManager = new FDBManExtra(PConfig.getSQLURL(), PConfig.getAdminDBPassword(), ActualDBName, PConfig.getAdminDBName(), FDBManExtra.DB_MYSQL_Selected);
        ColumnsName = DBManager.MYSQL_GetColumnsName(ActualDBTable);
        CLIOP = DBManager.LoadList_Table(ActualDBName, ActualDBTable, ColumnsName, ActualClient, ActualEnterprise);
        //ShowDInfo("Cargando datos ...");
    }

