    private void CreateTableChangesDetector() {

        DefaultTableModel TheModel = (DefaultTableModel) getJPTable().getModel();

        TheModel.addTableModelListener(new TableModelListener() {

            @Override
            public void tableChanged(TableModelEvent tme) {
                int tm = tme.getType();
                if (tme.getType() == TableModelEvent.UPDATE) {
                    TableUpdated = true;
                    firstRowupdated = tme.getFirstRow();
                    lastRowupdated = tme.getLastRow();
                }
            }
        });
    }

