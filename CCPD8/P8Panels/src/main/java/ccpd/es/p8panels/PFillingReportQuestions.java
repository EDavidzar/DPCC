    int GetAnswersCompleted() {
        int iCount = 0, iLastRow = 0;
        long lPreCalc;
        String sTmpExc = null, sTmpRes = null;

        iLastRow = TFLNAnswersList.size();
        // ph.start(iLastRow);
        lResAfir = 0;
        lResExc = 0;
        if (iLastRow > 0) {
            for (iCount = 0; iCount < iLastRow; iCount++) {
                NAlmRes Resp = TFLNAnswersList.get(iCount);
                sTmpRes = Integer.toString(Resp.getId_question());
                sTmpExc = Resp.getExcluded().toString();
                lPreCalc = 1 << iCount;

                if (CompareDBStr(sTmpRes, "1") == true) {
                    lResAfir |= lPreCalc;
                }
                if (CompareDBStr(sTmpExc, "1") == true) {
                    lResExc |= lPreCalc;
                }
                lPreCalc = 0;
            }
        } else {
            iLastRow = 1;
        }
        sTmpExc = null;
        sTmpRes = null;
        return iLastRow;
    }

