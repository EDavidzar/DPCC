    void NegativePressed() {
        int iARow = 0;
        long lPreCalc = 0, lResCalc = 0;
        iARow = ResIndex;
        lPreCalc = 1 << iARow;

        lResCalc = lResNeg & lPreCalc;

        // if (jRBNegative.isSelected() == true) {
        if (lResCalc != lPreCalc) {
            lResNeg = lResNeg + lPreCalc;
        }
        lResCalc = lResNeg & lPreCalc;
        if (lResCalc == lPreCalc) {
            lResAfir = lResAfir - lPreCalc;
        }
        lResCalc = lResExc & lPreCalc;
        if (lResCalc == lPreCalc) {
            lResExc = lResExc - lPreCalc;
        }
        jRBAfirmative.setSelected(false);
        jRBNoAplicable.setSelected(false);
        jRBNegative.setSelected(true);
        // }
        UpdateDataFrame();
    }

