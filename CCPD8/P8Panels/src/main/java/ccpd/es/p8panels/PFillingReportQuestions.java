            InsertFields.add(IField);
            IField = new CL_DBCV();
            //  IField.setsTableDBField("excluded");
            IField.setsValue(bexc.toString());
            InsertFields.add(IField);
            IField = new CL_DBCV();
            //  IField.setsTableDBField("id_client");
            IField.setsValue(idActualClient);
