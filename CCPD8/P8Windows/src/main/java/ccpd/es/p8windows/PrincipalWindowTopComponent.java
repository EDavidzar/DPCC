    public void UpdateInfoPanel() {
        if (PConfig.isUserAuthenticated()) {
            sStatus = " autenticado";
        } else {
            sStatus = " no autenticado";
        }
        String StatusInfo = "Usuario: " + ActualUser.getsNClient();
        StatusInfo = StatusInfo + "\nCliente: " + PConfig.getActualClient().getsNClient();
        StatusInfo = StatusInfo + "\nEmpresa: " + PConfig.getActualEnterprise().getsNEnterprise();
        StatusInfo = StatusInfo + "\nusuario " + sStatus;
        jTAInfoTextPanel.setText(StatusInfo);
    }

