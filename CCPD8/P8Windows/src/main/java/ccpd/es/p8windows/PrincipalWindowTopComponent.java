    @Override

    public void componentOpened() {

        if (!PConfig.isUserAuthenticated()) {
            AuthenticateUserProcedure();
        } else {
            sStatus = " autenticado";
        }
        if (!PConfig.isClientActivated()) {
            if (PConfig.getiClientsNumber() > 0) {
                ShowDError("Debe dar de alta un cliente para poder continuar ...");
            } else {
                ShowDError("Debe seleccionar un cliente para poder continuar ...");
            }
        }
        if (!PConfig.isEntityActivated()) {
            if (PConfig.getiEnterprisesNumber() > 0) {
                ShowDError("Debe dar de alta una empresa para poder continuar ...");
            } else {
                ShowDError("Debe seleccionar una empresa para poder continuar ...");
            }
        }
    }

