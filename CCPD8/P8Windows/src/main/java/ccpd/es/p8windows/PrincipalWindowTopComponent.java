    private void AuthenticateUserProcedure() {
        // PConfig.setHelpConfig("Autenticación de usuario", "autenticacion", "autenticacion.html");
        boolean authenticated = false;
        while (!authenticated) {

            AuthenticationDialog AD = new AuthenticationDialog(WindowManager.getDefault().getMainWindow(), true);
            AD.setAlwaysOnTop(true);
            AD.setLocationRelativeTo(WindowManager.getDefault().getMainWindow());
            AD.setVisible(true);
            authenticated = AD.isUserAuthenticated();
            boolean result = AD.isCancelaction();
            if (authenticated || result) {
                if (authenticated) {
                    ActualUser = AD.getActualUser();
                    PConfig.setUserAuthenticated(true);
                }
                UpdateInfoPanel();
                break;
            }
        }

    }

